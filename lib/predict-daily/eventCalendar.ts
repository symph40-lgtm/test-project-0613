// 다음 이벤트 조회 (문자 D-n 표기용): 오늘 이후 3일 내 이벤트 목록
export type UpcomingEvent = { kind: "FOMC" | "CPI" | "고용"; date: string; dDay: number };
export function upcomingEvents(todayKst: string, withinDays = 3): UpcomingEvent[] {
  const t = new Date(todayKst + "T00:00:00Z").getTime();
  const out: UpcomingEvent[] = [];
  const scan = (dates: string[], kind: UpcomingEvent["kind"]) => {
    for (const d of dates) {
      const dd = Math.round((new Date(d + "T00:00:00Z").getTime() - t) / 86400e3);
      if (dd >= 0 && dd <= withinDays) out.push({ kind, date: d, dDay: dd });
    }
  };
  scan(FOMC_DECISION_DATES, "FOMC");
  scan(CPI_RELEASE_DATES, "CPI");
  scan(ES_RELEASE_DATES, "고용");
  // 고용보고서 사전 일정이 없는 미래(2026+)는 첫 금요일 규칙으로 보강 (기존 NFP 게이트와 동일)
  if (!out.some((e) => e.kind === "고용")) {
    for (let dd = 0; dd <= withinDays; dd++) {
      const d = new Date(t + dd * 86400e3);
      if (d.getUTCDay() === 5 && d.getUTCDate() <= 7 && d.toISOString().slice(0, 10) > (ES_RELEASE_DATES[ES_RELEASE_DATES.length - 1] ?? "")) {
        out.push({ kind: "고용", date: d.toISOString().slice(0, 10), dDay: dd });
      }
    }
  }
  return out.sort((a, b) => a.dDay - b.dDay);
}
